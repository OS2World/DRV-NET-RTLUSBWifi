/* Milestone 2.4: enable BB, apply PHY_REG + AGC_TAB tables, trim crystal cap.
 * COM1: 'B' start, 'b' done. */
int rtl8188eu_config_bb(usb_dev_t *dev)
{
   USHORT v16, i;
   ULONG  xtal;

   tcom('B');
   /* enable BB before writing its registers (PHY_BBConfig8188E head). */
   v16 = rtw_read16(dev, 0x0002);              /* REG_SYS_FUNC_EN */
   rtw_write16(dev, 0x0002, (USHORT)(v16 | 0x2003)); /* BIT13|BIT1|BIT0 */
   rtw_write8(dev, 0x001F, 0x07);              /* REG_RF_CTRL RF_EN|RSTB|SDMRSTB */
   rtw_write8(dev, 0x0002, 0x17);              /* USBA|USBD|BB_GLB_RSTn|BBRSTB   */

   for (i = 0; i < (USHORT)G_BB_PHY_N; i++)    /* PHY_REG table */
      rtw_write32(dev, g_bb_phy[i].addr, g_bb_phy[i].val);
   for (i = 0; i < (USHORT)G_BB_AGC_N; i++)    /* AGC_TAB table */
      rtw_write32(dev, g_bb_agc[i].addr, g_bb_agc[i].val);

   /* CrystalCap trim, default 0x20: REG_AFE_XTAL_CTRL[22:11] = cap|cap<<6. */
   xtal = rtw_read32(dev, 0x0024);
   xtal = (xtal & ~0x007FF800UL) | 0x00410000UL;
   rtw_write32(dev, 0x0024, xtal);

   tcom('b');
   return 0;
}
