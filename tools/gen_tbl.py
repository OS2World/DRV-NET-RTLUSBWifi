import re, sys, os
REF = r'<path to 8821au-20210708-main>\hal\phydm\rtl8821a'   # edit
OUT = r'<path to this package>\rtl8821au\src\rtl8821_tbl.c'   # edit

# device parameters (check_positive of the Linux driver): USB interface, default board (no ext PA/LNA, no BT)
IFACE = 0x2
BOARD = 0x0
driver1 = ((IFACE & 0xF0) << 16) | ((IFACE & 0x0F) << 8) | BOARD   # platform bits are never tested by these tables
driver2 = 0
driver4 = 0

def check_positive(c1, c2, c3, c4):
    if (c1 & 0x0000F000) and (c1 & 0x0000F000) != (driver1 & 0x0000F000): return False
    if (c1 & 0x0F000000) and (c1 & 0x0F000000) != (driver1 & 0x0F000000): return False
    c1 &= 0x00FF0FFF
    d1 = driver1 & 0x00FF0FFF
    if (c1 & d1) == c1:
        if (c1 & 0x0F) == 0: return True
        mask = 0
        if c1 & 1: mask |= 0x000000FF
        if c1 & 2: mask |= 0x0000FF00
        if c1 & 4: mask |= 0x00FF0000
        if c1 & 8: mask |= 0xFF000000
        return (c2 & mask) == (driver2 & mask) and (c4 & mask) == (driver4 & mask)
    return False

def arr(fn, name):
    s = open(os.path.join(REF, fn), encoding='latin-1').read()
    m = re.search(r'u32 ' + name + r'\[\]\s*=\s*\{(.*?)\};', s, re.S)
    nums = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
    return list(zip(nums[0::2], nums[1::2]))

def flatten(pairs):
    out = []
    matched, skipped = True, False
    pre = (0, 0)
    for v1, v2 in pairs:
        if v1 & 0xC0000000:
            if v1 & 0x80000000:
                c = (v1 >> 28) & 3
                if c == 3: matched, skipped = True, False
                elif c == 2: matched = False if skipped else True
                else: pre = (v1, v2)
            else:
                if not skipped:
                    if check_positive(pre[0], pre[1], v1, v2): matched, skipped = True, True
                    else: matched, skipped = False, False
                else:
                    matched = False
        else:
            if matched: out.append((v1, v2))
    return out

mac = flatten(arr('halhwimg8821a_mac.c', 'array_mp_8821a_mac_reg'))
bb = flatten(arr('halhwimg8821a_bb.c', 'array_mp_8821a_phy_reg'))
agc = flatten(arr('halhwimg8821a_bb.c', 'array_mp_8821a_agc_tab'))
rf = flatten(arr('halhwimg8821a_rf.c', 'array_mp_8821a_radioa'))
print('mac', len(mac), 'bb', len(bb), 'agc', len(agc), 'rf', len(rf))
for n, t in (('mac', mac), ('bb', bb), ('agc', agc), ('rf', rf)):
    d = [a for a, v in t if 0xF9 <= (a & 0xFFF) <= 0xFE or a == 0xFFE]
    print(n, 'delay entries', len(d), [hex(x) for x in d][:8], 'max addr', hex(max(a for a, v in t)))

def emit(f, name, t, ctype, wide):
    f.write('const %s %s[%d] = {' % (ctype, name, len(t)) + chr(10))
    for i, (a, v) in enumerate(t):
        if (a & 0xFFF) == 0xFFE: a = 0xFE
        f.write('   {0x%X,0x%XUL},' % (a, v) if wide else '   {0x%X,0x%X},' % (a, v))
        if i % 4 == 3: f.write('\n')
    f.write('\n};\n')

